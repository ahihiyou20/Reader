// Writes out/sw.js after `next build` (NFR-03): precaches the app shell, keeps the 20 most recently
// opened articles and their covers for offline reading, and never touches Firebase or Google traffic.
import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';

const OUT = path.join(process.cwd(), 'out');

async function walk(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const e of await fs.readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}

async function main() {
  const files = await walk(OUT);
  const rel = (f: string) => '/' + path.relative(OUT, f).split(path.sep).join('/');
  const shell = files
    .map(rel)
    .filter(
      (f) =>
        (f.startsWith('/_next/static/') && /\.(js|css|woff2)$/.test(f)) ||
        ['/index.html', '/404.html', '/privacy.html', '/terms.html', '/manifest.webmanifest'].includes(f) ||
        f.startsWith('/icons/') ||
        ['/data/feed.json', '/data/categories.json', '/data/terms.json'].includes(f),
    );
  const hash = crypto.createHash('sha1');
  for (const f of shell.sort()) hash.update(f + (await fs.stat(path.join(OUT, f))).size);
  const version = hash.digest('hex').slice(0, 10);

  const sw = `/* Reader service worker · ${version} · generated by scripts/build-sw.ts */
const VERSION = ${JSON.stringify(version)};
const SHELL = 'reader-shell-' + VERSION;
const DATA = 'reader-data';
const ARTICLES = 'reader-articles';
const MEDIA = 'reader-media';
const PRECACHE = ${JSON.stringify(shell.map((f) => (f === '/index.html' ? '/' : f.replace(/\.html$/, ''))))};
const MAX_ARTICLES = 20;
const MAX_MEDIA = 60;
const MEDIA_HOSTS = ['images.unsplash.com', 'images.pexels.com', 'videos.pexels.com', 'upload.wikimedia.org', 'images-assets.nasa.gov', 'picsum.photos', 'fastly.picsum.photos'];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('reader-shell-') && k !== SHELL).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

async function trim(name, max) {
  const cache = await caches.open(name);
  const keys = await cache.keys();
  for (let i = 0; i < keys.length - max; i++) await cache.delete(keys[i]);
}

async function networkFirst(req, cacheName, fallback) {
  const cache = await caches.open(cacheName);
  try {
    const res = await fetch(req);
    if (res.ok) cache.put(req, res.clone());
    return res;
  } catch (e) {
    const hit = (await cache.match(req)) || (await caches.match(req, { ignoreSearch: true })) || (fallback && (await caches.match(fallback)));
    if (hit) return hit;
    throw e;
  }
}

async function staleWhileRevalidate(req, cacheName, max) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(req);
  const update = fetch(req)
    .then(async (res) => {
      if (res.ok) {
        await cache.delete(req); // re-insert so the newest entries stay at the end
        await cache.put(req, res.clone());
        if (max) trim(cacheName, max);
      }
      return res;
    })
    .catch(() => hit);
  return hit || update;
}

async function cacheFirst(req, cacheName, max) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(req);
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok || res.type === 'opaque') {
    cache.put(req, res.clone());
    trim(cacheName, max);
  }
  return res;
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === self.location.origin) {
    if (url.pathname.startsWith('/__/') || url.pathname.startsWith('/cms') || url.pathname.startsWith('/preview')) return;
    if (req.mode === 'navigate') return event.respondWith(networkFirst(req, DATA, '/'));
    if (url.pathname.startsWith('/_next/static/') || url.pathname.startsWith('/icons/')) return event.respondWith(cacheFirst(req, SHELL, 500));
    if (url.pathname.startsWith('/data/articles/')) return event.respondWith(staleWhileRevalidate(req, ARTICLES, MAX_ARTICLES));
    if (url.pathname.startsWith('/data/')) return event.respondWith(networkFirst(req, DATA));
    if (url.pathname.startsWith('/covers/')) return event.respondWith(cacheFirst(req, MEDIA, MAX_MEDIA));
    return;
  }
  if (MEDIA_HOSTS.includes(url.hostname) && req.destination === 'image') return event.respondWith(cacheFirst(req, MEDIA, MAX_MEDIA));
});
`;
  await fs.writeFile(path.join(OUT, 'sw.js'), sw);
  console.log(`sw.js: ${shell.length} files precached, version ${version}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
